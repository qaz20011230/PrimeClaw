#!/usr/bin/env python3
"""selftest.py -- self-tests for the analyst tooling (pmgap.py / fast_stats.c).

Everything runs on synthetic PRMGAP01 v1 datasets generated by
make_synthetic.py under reports/_selftest/.  No real dataset is needed.

Coverage
--------
1. Reference sieve cross-checks, including the known constants
   pi(10^4) = 1229 and pi(10^5) = 9592.
2. Six different synthetic datasets (chunk_primes = 1, 2, 7, 100, 10000, all)
   covering single-prime blocks, block boundaries and one-block-per-file.
3. Full decode of every dataset equals the reference prime list.
4. pi(t) table equals reference counts; targets beyond the saved bound are
   correctly flagged non-exact.
5. First-N decimal text artifact: content, line count, last line.
6. Prefix gap/residue statistics equal an independent reference computation
   with identical within-block semantics.
7. Negative tests: bad magic, bad version, broken prev_prime chain, wrong
   end_prime, wrong count, wrong nbytes, corrupted gap byte, truncated tail,
   trailing garbage -- all must raise FormatError in strict mode; incomplete
   tails must be tolerated in lenient mode.
8. Optional C accelerator cross-check (fast_stats) when the binary is built.

Exit code 0 iff every check passes.
"""

from __future__ import annotations

import json
import math
import os
import shutil
import struct
import subprocess
import sys
from bisect import bisect_right

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import make_synthetic  # noqa: E402
import pmgap  # noqa: E402

WORKDIR = os.path.join(HERE, "_selftest")
C_BINARY = os.path.join(HERE, "fast_stats")

REFERENCE_LIMIT = 100_003          # 100003 is prime -> covers pi(10^5)
EXPECTED_PI_1E4 = 1229
EXPECTED_PI_1E5 = 9592


class Checker:
    def __init__(self):
        self.passed = 0
        self.failed = []

    def section(self, name):
        print("\n== %s ==" % name)

    def check(self, name, condition, detail=""):
        if condition:
            self.passed += 1
            return True
        self.failed.append((name, detail))
        print("  FAIL %s%s" % (name, (": " + detail) if detail else ""))
        return False

    def eq(self, name, got, want):
        return self.check(name, got == want, "got %r, want %r" % (got, want))

    def summary(self):
        print("\n%d checks passed, %d failed" % (self.passed, len(self.failed)))
        for name, detail in self.failed:
            print("  FAILED: %s (%s)" % (name, detail))
        return not self.failed


# ---------------------------------------------------------------------------
# Reference computation (plain Python lists, independent of the decoder)
# ---------------------------------------------------------------------------

def ref_prefix_stats(primes, chunk_primes, max_prime):
    blocks = make_synthetic.partition_blocks(primes, chunk_primes)
    primes_counted = 0
    residue_mod3 = [0, 0, 0]
    residue_mod4 = [0, 0, 0, 0]
    first_counted = None
    last_counted = None
    for p in primes:
        if p <= max_prime:
            primes_counted += 1
            if first_counted is None:
                first_counted = p
            last_counted = p
            residue_mod3[p % 3] += 1
            residue_mod4[p % 4] += 1
    gaps = []                      # ordered (gap, start, end) triples
    blocks_scanned = 0
    cross_gaps_included = 0
    previous_end = None
    for group in blocks:
        if group[0] > max_prime:
            break
        blocks_scanned += 1
        if previous_end is not None:
            # cross-block gap recovered from the two header endpoints
            gaps.append((group[0] - previous_end, previous_end, group[0]))
            cross_gaps_included += 1
        for a, b in zip(group, group[1:]):
            if b <= max_prime:
                gaps.append((b - a, a, b))
        previous_end = group[-1]
    max_gap = None
    max_gap_start = None
    max_gap_end = None
    for g, a, b in gaps:
        if max_gap is None or g > max_gap:
            max_gap, max_gap_start, max_gap_end = g, a, b
    return {
        "primes_counted": primes_counted,
        "first_prime_counted": first_counted,
        "last_prime_counted": last_counted,
        "blocks_scanned": blocks_scanned,
        "gaps_counted": len(gaps),
        "gap_sum": sum(g for g, _, _ in gaps),
        "max_gap": max_gap,
        "max_gap_start": max_gap_start,
        "max_gap_end": max_gap_end,
        "twin_pairs": sum(1 for g, _, _ in gaps if g == 2),
        "residue_mod3": residue_mod3,
        "residue_mod4": residue_mod4,
        "cross_block_gaps_included": cross_gaps_included,
    }


def read_all_blocks(path):
    with open(path, "rb") as fp:
        return list(pmgap.iter_blocks(fp, decode_payload=False, strict=True,
                                      allow_incomplete_tail=False))


def expect_format_error(path, *, allow_incomplete_tail=False):
    """Run a full decode; return (raised_format_error, message)."""
    try:
        with open(path, "rb") as fp:
            for block in pmgap.iter_blocks(fp, decode_payload=True, strict=True,
                                           allow_incomplete_tail=allow_incomplete_tail):
                for _ in pmgap.iter_block_primes(block):
                    pass
    except pmgap.FormatError as exc:
        return True, str(exc)
    except Exception as exc:  # noqa: BLE001 - want a clear self-test failure
        return False, "wrong exception type %s: %s" % (type(exc).__name__, exc)
    return False, "no FormatError raised"


# ---------------------------------------------------------------------------
# Test body
# ---------------------------------------------------------------------------

def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--keep" not in argv:
        if os.path.isdir(WORKDIR):
            shutil.rmtree(WORKDIR)
    os.makedirs(WORKDIR, exist_ok=True)

    c = Checker()

    # -- reference sieve ----------------------------------------------------
    c.section("reference sieve")
    primes = make_synthetic.sieve_primes(REFERENCE_LIMIT)
    c.eq("reference last prime", primes[-1], REFERENCE_LIMIT)
    c.eq("pi(10^4) reference", bisect_right(primes, 10_000), EXPECTED_PI_1E4)
    c.eq("pi(10^5) reference", bisect_right(primes, 100_000), EXPECTED_PI_1E5)
    c.eq("reference count <= 100003", len(primes), EXPECTED_PI_1E5 + 1)

    datasets = {}

    # -- per-dataset checks -------------------------------------------------
    for chunk in (1, 2, 7, 100, 10_000, len(primes)):
        path = os.path.join(WORKDIR, "synthetic_100003_chunk%d.pmgap" % chunk)
        info = make_synthetic.write_dataset(path, primes, chunk_primes=chunk)
        datasets[chunk] = path
        c.section("synthetic dataset chunk_primes=%d (%d blocks, %d bytes)"
                  % (chunk, info["blocks"], info["file_size"]))

        summary = pmgap.dataset_summary(path, strict=True, allow_incomplete_tail=False)
        expected_blocks = 1 + math.ceil((len(primes) - 1) / chunk)
        c.eq("block count", summary["block_count"], expected_blocks)
        c.eq("total primes", summary["total_primes"], len(primes))
        c.eq("first prime", summary["first_prime"], 2)
        c.eq("last prime", summary["last_prime"], primes[-1])
        c.check("file complete", summary["complete"] and summary["incomplete_tail"] is None,
                repr(summary["incomplete_tail"]))
        c.eq("file size == 32 + 48*blocks + payload",
             summary["file_size"], summary["expected_file_size"])

        decoded = []
        with open(path, "rb") as fp:
            for block in pmgap.iter_blocks(fp, decode_payload=True, strict=True,
                                           allow_incomplete_tail=False):
                decoded.extend(pmgap.iter_block_primes(block))
        c.eq("full decode equals reference prime list", decoded, primes)

        verify = pmgap.verify_full(path, strict=True, allow_incomplete_tail=False)
        c.eq("verify_full total", verify["total_primes"], len(primes))
        c.eq("verify_full last", verify["last_prime"], primes[-1])

        # pi table, including known constants
        targets = [1, 2, 3, 4, 10, 100, 1_000, 10_000, 100_000, REFERENCE_LIMIT]
        pi_result = pmgap.compute_pi_table(path, targets, strict=True,
                                           allow_incomplete_tail=False)
        for t in targets:
            want = bisect_right(primes, t)
            got = pi_result["targets"][t]
            c.check("pi(%d) exact" % t, got["exact"], repr(got))
            c.eq("pi(%d)" % t, got["pi"], want)
        c.eq("pi(10^4) == %d" % EXPECTED_PI_1E4, pi_result["targets"][10_000]["pi"], EXPECTED_PI_1E4)
        c.eq("pi(10^5) == %d" % EXPECTED_PI_1E5, pi_result["targets"][100_000]["pi"], EXPECTED_PI_1E5)
        beyond = pmgap.compute_pi_table(path, [REFERENCE_LIMIT + 1], strict=True,
                                        allow_incomplete_tail=False)
        c.check("pi(beyond saved bound) flagged non-exact",
                beyond["targets"][REFERENCE_LIMIT + 1]["exact"] is False
                and beyond["targets"][REFERENCE_LIMIT + 1]["pi"] is None)

        # first-N text artifact
        text_path = os.path.join(WORKDIR, "first_1000_chunk%d.txt" % chunk)
        written = pmgap.write_first_primes(path, text_path, 1000, strict=True,
                                           allow_incomplete_tail=False)
        c.eq("first-N written count", written["written"], 1000)
        c.eq("first-N last prime", written["last_prime"], primes[999])
        verdict = pmgap.verify_first_primes_file(text_path, 1000, expect_last=primes[999])
        c.check("first-N file verifies", verdict["ok"], repr(verdict))
        with open(text_path, "r", encoding="ascii") as fp:
            text_lines = [int(x) for x in fp.read().split()]
        c.eq("first-N lines equal reference", text_lines, primes[:1000])

        # prefix statistics at several cut points
        for max_prime in (1_000, 10_000, 100_000, primes[-1]):
            stats = pmgap.scan_prefix_stats(path, max_prime, strict=True,
                                            allow_incomplete_tail=False)
            ref = ref_prefix_stats(primes, chunk, max_prime)
            c.eq("stats[%d] primes_counted" % max_prime,
                 stats["primes_counted"], ref["primes_counted"])
            c.eq("stats[%d] first prime" % max_prime,
                 stats["first_prime_counted"], ref["first_prime_counted"])
            c.eq("stats[%d] last prime" % max_prime,
                 stats["last_prime_counted"], ref["last_prime_counted"])
            c.eq("stats[%d] blocks_scanned" % max_prime,
                 stats["blocks_scanned"], ref["blocks_scanned"])
            c.eq("stats[%d] gaps_counted" % max_prime,
                 stats["gaps_counted"], ref["gaps_counted"])
            c.eq("stats[%d] gap_sum" % max_prime, stats["gap_sum"], ref["gap_sum"])
            c.eq("stats[%d] max_gap" % max_prime, stats["max_gap"], ref["max_gap"])
            c.eq("stats[%d] max_gap_start" % max_prime,
                 stats["max_gap_start"], ref["max_gap_start"])
            c.eq("stats[%d] max_gap_end" % max_prime,
                 stats["max_gap_end"], ref["max_gap_end"])
            c.eq("stats[%d] twin_pairs" % max_prime,
                 stats["twin_pairs"], ref["twin_pairs"])
            c.eq("stats[%d] residue mod 3" % max_prime,
                 stats["residue_mod3"], ref["residue_mod3"])
            c.eq("stats[%d] residue mod 4" % max_prime,
                 stats["residue_mod4"], ref["residue_mod4"])
            c.eq("stats[%d] cross-block gaps included" % max_prime,
                 stats["cross_block_gaps_included"], ref["cross_block_gaps_included"])
            c.check("stats[%d] target covered" % max_prime, stats["target_covered"])

    # -- special small datasets --------------------------------------------
    c.section("special small datasets")
    only2 = os.path.join(WORKDIR, "only_prime_2.pmgap")
    make_synthetic.write_dataset(only2, [2], chunk_primes=5)
    s = pmgap.dataset_summary(only2, strict=True, allow_incomplete_tail=False)
    c.eq("only-2 total primes", s["total_primes"], 1)
    c.eq("only-2 last prime", s["last_prime"], 2)
    c.eq("only-2 block count", s["block_count"], 1)
    with open(only2, "rb") as fp:
        c.eq("only-2 decoded list", list(pmgap.iter_primes(fp)), [2])
    pi2 = pmgap.compute_pi_table(only2, [1, 2, 3], strict=True, allow_incomplete_tail=False)
    c.eq("only-2 pi(2)", pi2["targets"][2]["pi"], 1)
    c.check("only-2 pi(3) beyond bound not exact", pi2["targets"][3]["exact"] is False)

    up3 = os.path.join(WORKDIR, "primes_2_3.pmgap")
    make_synthetic.write_dataset(up3, [2, 3], chunk_primes=5)
    with open(up3, "rb") as fp:
        c.eq("2,3 decoded list", list(pmgap.iter_primes(fp)), [2, 3])
    pi3 = pmgap.compute_pi_table(up3, [2, 3, 4], strict=True, allow_incomplete_tail=False)
    c.eq("2,3 pi(3)", pi3["targets"][3]["pi"], 2)
    c.check("2,3 pi(4) beyond bound not exact", pi3["targets"][4]["exact"] is False)

    # -- negative / corruption tests ---------------------------------------
    c.section("corruption and negative tests")
    base_path = datasets[100]
    with open(base_path, "rb") as fp:
        base_bytes = fp.read()
    blocks = read_all_blocks(base_path)
    c.check("base dataset has multiple blocks", len(blocks) > 3, str(len(blocks)))

    def make_variant(name, mutate=None, raw=None):
        data = raw if raw is not None else bytes(base_bytes)
        if mutate is not None:
            buf = bytearray(data)
            mutate(buf)
            data = bytes(buf)
        path = os.path.join(WORKDIR, "corrupt_%s.pmgap" % name)
        with open(path, "wb") as fp:
            fp.write(data)
        return path

    def check_rejected(name, path):
        raised, message = expect_format_error(path)
        return c.check(name, raised, message)

    block1 = blocks[1]
    block2 = blocks[2]

    def set_byte(offset, value):
        def mutate(buf):
            buf[offset] = value
        return mutate

    def set_u32(offset, value):
        def mutate(buf):
            struct.pack_into("<I", buf, offset, value)
        return mutate

    def set_u64(offset, value):
        def mutate(buf):
            struct.pack_into("<Q", buf, offset, value)
        return mutate

    check_rejected("bad global magic", make_variant("global_magic", set_byte(0, ord("X"))))
    check_rejected("bad global version", make_variant("global_version", set_u32(8, 2)))
    check_rejected("bad block magic", make_variant("block_magic", set_byte(block1.offset, ord("X"))))
    check_rejected("broken prev_prime chain",
                   make_variant("chain", set_u64(block2.offset + 8, block2.prev_prime + 2)))
    check_rejected("wrong end_prime",
                   make_variant("end_prime", set_u64(block1.offset + 24, block1.end_prime + 2)))
    check_rejected("wrong count (too many)",
                   make_variant("count", set_u64(block1.offset + 32, block1.count + 1)))
    check_rejected("wrong nbytes (one byte short)",
                   make_variant("nbytes", set_u64(block1.offset + 40, block1.nbytes - 1)))
    check_rejected("corrupted gap parity",
                   make_variant("gap_parity", set_byte(block1.payload_offset, base_bytes[block1.payload_offset] ^ 1)))
    check_rejected("bad first block fields",
                   make_variant("first_block", set_u64(32 + 16, 4)))

    truncated = make_variant("truncated_tail", raw=base_bytes[:-3])
    check_rejected("truncated tail rejected in strict mode", truncated)
    lenient = pmgap.dataset_summary(truncated, strict=True, allow_incomplete_tail=True)
    c.check("truncated tail tolerated in lenient mode",
            lenient["incomplete_tail"] is not None and not lenient["complete"],
            repr(lenient["incomplete_tail"]))
    c.eq("truncated lenient block count", lenient["block_count"], len(blocks) - 1)
    c.eq("truncated lenient total primes", lenient["total_primes"],
         len(primes) - blocks[-1].count)
    lenient_stats = pmgap.scan_prefix_stats(truncated, 10_000, strict=True,
                                            allow_incomplete_tail=True)
    c.eq("truncated lenient stats still correct", lenient_stats["primes_counted"],
         bisect_right(primes, 10_000))

    garbage = make_variant("trailing_garbage", raw=base_bytes + b"\x00" * 10)
    check_rejected("trailing garbage rejected in strict mode", garbage)
    garbage_summary = pmgap.dataset_summary(garbage, strict=True, allow_incomplete_tail=True)
    c.check("trailing garbage flagged as tail",
            garbage_summary["incomplete_tail"] is not None
            and garbage_summary["incomplete_tail"]["tail_bytes"] == 10,
            repr(garbage_summary["incomplete_tail"]))
    c.eq("trailing garbage keeps prime count", garbage_summary["total_primes"], len(primes))

    # -- optional C accelerator cross-check --------------------------------
    c.section("C accelerator cross-check")
    if os.path.exists(C_BINARY) and os.access(C_BINARY, os.X_OK):
        dataset = datasets[100]
        targets = [10, 100, 1_000, 10_000, 100_000, REFERENCE_LIMIT]
        c_json = os.path.join(WORKDIR, "c_stats.json")
        c_first = os.path.join(WORKDIR, "c_first_1000.txt")
        cmd = [C_BINARY, dataset,
               "--max", "100000",
               "--pi", ",".join(str(t) for t in targets),
               "--first-n", "1000",
               "--first-out", c_first,
               "--json", c_json]
        proc = subprocess.run(cmd, capture_output=True, text=True)
        if not c.check("C tool exit code 0", proc.returncode == 0,
                       (proc.stderr or proc.stdout)[-800:]):
            pass
        else:
            with open(c_json, "r", encoding="utf-8") as fp:
                cj = json.load(fp)
            py_stats = pmgap.scan_prefix_stats(dataset, 100_000, strict=True,
                                               allow_incomplete_tail=False)
            for key in ("primes_counted", "gaps_counted", "gap_sum", "max_gap",
                        "max_gap_start", "max_gap_end", "twin_pairs",
                        "blocks_scanned", "last_prime_counted"):
                c.eq("C vs Python stats.%s" % key, cj["stats"][key], py_stats[key])
            c.eq("C vs Python stats.residue_mod3",
                 cj["stats"]["residue_mod3"], py_stats["residue_mod3"])
            c.eq("C vs Python stats.residue_mod4",
                 cj["stats"]["residue_mod4"], py_stats["residue_mod4"])
            c.eq("C vs Python summary.total_primes", cj["total_primes"], len(primes))
            c.eq("C vs Python summary.last_prime", cj["last_prime"], primes[-1])
            pi_py = pmgap.compute_pi_table(dataset, targets, strict=True,
                                           allow_incomplete_tail=False)
            for t in targets:
                c.eq("C vs Python pi(%d)" % t,
                     cj["pi"][str(t)], pi_py["targets"][t]["pi"])
            with open(c_first, "r", encoding="ascii") as fp:
                c_lines = [int(x) for x in fp.read().split()]
            c.eq("C first-N lines equal reference", c_lines, primes[:1000])
    else:
        print("  SKIP: fast_stats not built yet; build it with make -C reports fast_stats "
              "and re-run selftest to cross-check the C engine.")

    # -- verdict ------------------------------------------------------------
    print("\n" + "=" * 70)
    if c.summary():
        print("SELFTEST: ALL PASS")
        return 0
    print("SELFTEST: FAILURES PRESENT")
    return 1


if __name__ == "__main__":
    sys.exit(main())
